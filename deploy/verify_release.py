#!/usr/bin/env python3
"""Check archive integrity and paths before extracting into a new pilot release."""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import tarfile

ALLOWED = {"core", "rdbhs_backoffice", "templates", "manage.py", "pyproject.toml", "uv.lock", "README.md", ".python-version"}


def verify(bundle, expected_commit=None):
    manifest = json.loads((bundle / "release.json").read_text())
    if manifest.get("schema") != 1 or manifest.get("project") != "rdbhs-backoffice":
        raise ValueError("Unsupported manifest")
    sha = manifest.get("commit", "")
    if not re.fullmatch(r"[0-9a-f]{40}", sha) or (expected_commit and sha != expected_commit):
        raise ValueError("Commit mismatch")
    if manifest.get("archive") != "application.tar.gz":
        raise ValueError("Unexpected archive name")
    archive = bundle / manifest["archive"]
    if hashlib.sha256(archive.read_bytes()).hexdigest() != manifest.get("sha256"):
        raise ValueError("Archive checksum mismatch")
    with tarfile.open(archive, "r:gz") as tar:
        files = {}
        total = 0
        for member in tar.getmembers():
            path = PurePosixPath(member.name)
            if path.is_absolute() or ".." in path.parts or not path.parts or path.parts[0] not in ALLOWED:
                raise ValueError("Unsafe archive path")
            if not (member.isfile() or member.isdir()):
                raise ValueError("Archive links and special files are forbidden")
            if any(part in {".env", ".git", ".venv", "entra-secrets.env"} for part in path.parts):
                raise ValueError("Forbidden archive content")
            if member.isfile():
                if str(path) in files:
                    raise ValueError("Duplicate archive member")
                total += member.size
                if total > 50 * 1024 * 1024:
                    raise ValueError("Unexpected archive size")
                files[str(path)] = tar.extractfile(member).read()
    for required in ("manage.py", "pyproject.toml", "uv.lock", "rdbhs_backoffice/settings.py"):
        if required not in files:
            raise ValueError("Incomplete archive")
    if hashlib.sha256(files["uv.lock"]).hexdigest() != manifest.get("lock_sha256"):
        raise ValueError("Lockfile checksum mismatch")
    return manifest, files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("bundle", type=Path)
    parser.add_argument("--expected-commit")
    parser.add_argument("--extract", type=Path)
    args = parser.parse_args()
    manifest, files = verify(args.bundle, args.expected_commit)
    if args.extract:
        # Pilot root is generated by the harness; never extract to a supplied VPS path.
        target = args.extract
        if target.is_symlink() or target.exists():
            raise ValueError("Extraction requires a new directory")
        target.mkdir(parents=True, mode=0o700)
        for name, content in files.items():
            output = target / name
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_bytes(content)
            output.chmod(0o600)
    print(json.dumps(manifest))


if __name__ == "__main__":
    main()
